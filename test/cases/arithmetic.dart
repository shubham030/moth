void main() {
  print(7 + 3);
  print(7 - 10);
  print(6 * 7);
  print(7 / 2); // Dart: / is always double
  print(7 ~/ 2);
  print(-7 ~/ 2);
  print(7 % 3);
  print(-7 % 3); // Dart: result takes the sign of the divisor
  print(7 % -3);
  print(2.5 * 4);
  print(1 + 2.5);
  print(-(3 + 4));
  print(10 ~/ 3 * 3 + 10 % 3);
}
